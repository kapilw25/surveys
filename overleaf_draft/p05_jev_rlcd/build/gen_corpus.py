def tab_compare_contract(rows):
    # stated rule: every work whose confidence is attached to a typed decision (any stage), plus the X-stage works on
    # constrained (grammar- or schema-bound) output. Contributions are in Tables 3 and 8, so this table lists placement and
    # evidence only. Cal. = the main text reports ECE, Brier, NLL or a reliability diagram (literature/contract_labels.tsv).
    x=[r for r in rows if r["output_contract"]=="typed-decision" or (r["stage"]=="X" and r["output_contract"]=="constrained")]
    typed=[r for r in x if r["output_contract"]=="typed-decision"]
    bad=[r["cite"] for r in typed if r.get("reports_cal") not in ("yes","no")]
    if bad: raise SystemExit(f"typed works without a recorded calibration-metric check (contract_labels.tsv): {bad}")
    tcal=sum(1 for r in typed if r["reports_cal"]=="yes")
    core=[r for r in typed if r["stage"]=="S4"]; ccal=sum(1 for r in core if r["reports_cal"]=="yes")
    order=["typed-decision","constrained"]
    x=sorted(x,key=lambda r:(order.index(r["output_contract"]),STAGES.index(r["stage"]),r["group"],r["y"] or 0,r["cite"]))
    body=[]; cur=None
    for r in x:
        key=(r["output_contract"],r["stage"])
        if key!=cur:
            cur=key; n=sum(1 for q in x if (q["output_contract"],q["stage"])==key)
            body.append(rf"\midrule\multicolumn{{5}}{{@{{}}l}}{{\textbf{{{cap(contract_label(r['output_contract']))} output, {esc(SNAME[r['stage']])}}} ({n})}} \\*")
        fam=TNAME[r["tfam"]] if r["stage"]=="S4" and r.get("tfam") in TNAME else r["group"]
        calc=(r"\yy" if r["reports_cal"]=="yes" else r"\ab") if r["output_contract"]=="typed-decision" else ""
