#!/usr/bin/env python3
r"""fig2: the grouped-cell taxonomy, generated from literature/corpus.tsv (families from literature/s4_families.tsv).

Selection rule (stated in the caption): at S4 (the core) up to S4CAP works per training family, evenly spaced over the
family's works in year order; for every other family, its earliest and its latest work; the theory and analysis works are
listed in full. Each line is "\textbf{method name or first author}: trimmed real title \citep{key}"; the citation carries
the year, so the label does not repeat one.
"""
import csv, os, re, sys
from collections import OrderedDict
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from p05_common import STAGES, SNAME, TFAMS, TNAME, esc, brit
P=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BG=2; S4CAP=8; BUDGET=84; CELLW="40em"
def line(r):
    t=re.sub(r"\s+"," ",r["title"]).strip()
    fa=r["first_author"] or "?"; last=fa.split(",")[0] if "," in fa else fa.split()[-1]
    if ":" in t and len(t.split(":")[0])<=28: name,rest=t.split(":",1); rest=rest.strip()
    else: name,rest=last,t
    room=int(BUDGET-1.15*len(name)-2-(len(last)+16))
    cut=len(rest)>room
    if cut: rest=rest[:max(room-2,12)].rsplit(" ",1)[0].rstrip(",;:")
    return rf"\textbf{{{esc(name)}}}: {esc(rest)}{r'\ldots' if cut else ''}~\citep{{{r['cite']}}}"
def pick_bg(fr):
    fr=sorted(fr,key=lambda r:(int(r["year"] or 0),r["cite"]))
    return fr if len(fr)<=BG else [fr[0],fr[-1]]
def wrap(s,n=21):
    out=[""]
    for w_ in s.split():
        if out[-1] and len(out[-1])+1+len(w_)>n: out.append(w_)
        else: out[-1]=(out[-1]+" "+w_).strip()
    return "\\\\".join(out)
def lab(s): return "\\\\".join(r"\textbf{"+x.strip()+"}" for x in s.split("\\\\"))
def cell(rows,fill): return "[{"+"\\\\".join(line(r) for r in rows)+"}, fill="+fill+", text width="+CELLW+", align=left]"
def main():
    rows=list(csv.DictReader(open(os.path.join(P,"literature","corpus.tsv"),encoding="utf-8"),delimiter="\t"))
    listed=0; s4listed=0; out=[]
    for s in STAGES:
        grp=[r for r in rows if r["stage"]==s]
        if not grp: continue
        out.append("  ["+lab(wrap(esc(SNAME[s]),14))+f", fill=st{s}!40, text width=9em")
        if s=="S4":
            for T in TFAMS:
                fr=sorted([r for r in grp if r["tfam"]==T],key=lambda r:(int(r["year"] or 0),r["cite"]))
                if not fr: continue
                out.append("    ["+lab(wrap(esc(TNAME[T]),18))+f", fill=stS4!30, text width=10.5em")
                sel=fr if len(fr)<=S4CAP else [fr[round(i*(len(fr)-1)/(S4CAP-1))] for i in range(S4CAP)]
                out.append("      "+cell(sel,"stS4!8")); out.append("    ]"); listed+=len(sel); s4listed+=len(sel)
        elif s=="TH":
            sel=sorted(grp,key=lambda r:(int(r["year"] or 0),r["cite"])); out.append("    "+cell(sel,f"st{s}!15")); listed+=len(sel)
        else:
            fams=OrderedDict()
            for r in sorted(grp,key=lambda r:r["group"]): fams.setdefault(r["group"],[]).append(r)
            for fam,fr in fams.items():
                sel=pick_bg(fr)
                out.append("    ["+lab(wrap(esc(brit(fam[:1].upper()+fam[1:]))))+f", fill=st{s}!22, text width=12.5em")
                out.append("      "+cell(sel,f"st{s}!7")); out.append("    ]"); listed+=len(sel)
        out.append("  ]")
    n=len(rows); s4=sum(1 for r in rows if r["stage"]=="S4"); nth=sum(1 for r in rows if r["stage"]=="TH")
    tex=r"""% AUTO-GENERATED by build/gen_taxonomy.py from literature/corpus.tsv -- do not hand-edit.
\begin{figure*}[p]
\centering
\resizebox{!}{0.84\textheight}{%
\begin{forest}
  for tree={align=center},
  where n children=0{font=\footnotesize, align=left}{font=\normalsize},
  where level=1{font=\large}{},
  where level=0{font=\Large}{},
[\textbf{Calibration-aware}\\\textbf{decision-making}\\\textbf{with language}\\\textbf{models}, fill=black!8, text width=12em
"""+"\n".join(out)+r"""
]
\end{forest}}
\caption{\textbf{A taxonomy of calibration-aware decision-making with language models} ("""+str(listed)+r""" of the """+str(n)+r"""
works in Tables~\ref{tab:compare_s4} and~\ref{tab:landscape}). Branches are the stage at which calibration enters (Table~\ref{tab:definitions}); X holds
the works that consume a confidence or fix the output contract. The core, S4 ("""+str(s4)+r""" works), is grouped by what the
training signal scores and lists up to """+str(S4CAP)+r""" works per family, evenly spaced over the family's works in year order
("""+str(s4listed)+r""" shown; all are in Table~\ref{tab:compare_s4}). The """+str(nth)+r""" theory and analysis works are listed in
full and are not counted in the core. Every other family lists its earliest and its latest work. Each line gives a trimmed form
of the paper's own title; a citation may show a later venue year than the first-version year counted in
Figures~\ref{fig:corpus_dist} and~\ref{fig:stage_trend}.}
\Description{A tree diagram rooted at calibration-aware decision-making with language models, with branches for read-off,
post-hoc maps, prompt elicitation, extra inference, training (split into five families by what the training signal scores),
theory and analysis, and consumers and output contract. Each family cell lists papers with short titles.}
\label{fig:taxonomy_main}
\end{figure*}
"""
    open(os.path.join(P,"figures","fig_taxonomy_main.tex"),"w",encoding="utf-8").write(tex)
    print(f"taxonomy: {listed} of {n} works listed (S4 core {s4}, shown {s4listed}; theory {nth})")
if __name__=="__main__": main()
