#!/usr/bin/env python3
r"""Build the full paper, main.pdf, from main.tex + sections/ + the generated figures and tables.

  python3 build/build_paper.py

Steps: sections/numbers.tex (gen_numbers.py) -> styles/stage_colors.tex (p05_common) -> pdflatex -> bibtex ->
pdflatex x2 in the paper root. Reports pages, errors, undefined references and citations, overfull boxes, and
checks that each float prints the number its deliverable carries (Figures 1-11, Tables 1-8, A1, A2).
"""
import os, re, subprocess, sys
P=os.path.dirname(os.path.dirname(os.path.abspath(__file__))); B=os.path.join(P,"build")
sys.path.insert(0,B)
from p05_common import stage_tex_colors
def run(c): return subprocess.run(c,cwd=P,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
def main():
    subprocess.run([sys.executable,os.path.join(B,"gen_numbers.py")],check=True,stdout=subprocess.DEVNULL)
    # layout rule (owner, 2026-09-28): a table longer than one page (a longtable) belongs in the appendix
    body=[f for f in sorted(os.listdir(os.path.join(P,"sections"))) if f.endswith(".tex") and f not in ("appendix.tex","numbers.tex")]
    longs_in_body=[(f,t) for f in body for t in re.findall(r"\\input\{(tables/[^}]+)\}",open(os.path.join(P,"sections",f)).read())
                   if "longtable" in open(os.path.join(P,t+".tex")).read()]
    if longs_in_body: raise SystemExit(f"multi-page tables must go to the appendix: {longs_in_body}")
    open(os.path.join(P,"styles","stage_colors.tex"),"w").write("% AUTO-GENERATED by build/build_paper.py from build/p05_common.py\n"+stage_tex_colors()+"\n")
    for f in ("main.aux","main.bbl"):
        if os.path.exists(os.path.join(P,f)): os.remove(os.path.join(P,f))
    tex=["pdflatex","-interaction=nonstopmode","main.tex"]
    run(tex); run(["bibtex","main"]); run(tex); run(tex)
    for _ in range(3):                      # longtables and labels settle over extra passes
        lg=open(os.path.join(P,"main.log"),errors="replace").read()
        if "Rerun LaTeX" not in lg and "Rerun to get" not in lg and "may have changed" not in lg: break
        run(tex)
    log=open(os.path.join(P,"main.log"),errors="replace").read()
    pages=subprocess.run(["pdfinfo",os.path.join(P,"main.pdf")],capture_output=True,text=True).stdout
    pages=pages.split("Pages:")[1].split()[0] if "Pages:" in pages else "?"
    und=[l.strip() for l in log.splitlines() if "undefined" in l and "Warning" in l and "There were" not in l]
    over=re.findall(r"Overfull \\hbox \((\d+\.\d+)pt too wide\)[^\n]*lines (\d+--\d+)",log)
    errs=log.count("\n! ")
    big=re.findall(r"Float too large for page by ([\d.]+)pt",log)   # the deliverable build (preview) cannot see this
    # float numbers: each label must resolve to its deliverable number
    aux=open(os.path.join(P,"main.aux"),errors="replace").read()
    want={"fig:hero_collage":"1","fig:taxonomy_main":"2","fig:survey_timeline":"3","fig:prisma":"4","fig:corpus_overview":"5",
          "fig:corpus_dist":"6","fig:stage_trend":"7","fig:method_gallery":"8","fig:results_gallery":"9","fig:decision_loop":"10",
          "fig:future_protocol":"11","tab:jev_hf_ecosystem":"1","tab:jev_decision_index":"2","tab:stage_limits":"3","tab:future_metrics":"4",
          "tab:definitions":"A1","tab:survey_compare":"B1","tab:compare_s4":"C1","tab:compare_contract":"D1",
          "tab:panel_provenance":"E1","tab:landscape":"F1"}
    bad=[]
    for lab,num in want.items():
        m=re.search(r"\\newlabel\{"+re.escape(lab)+r"\}\{\{([^}]*)\}",aux)
        got=m.group(1) if m else "missing"
        if got!=num: bad.append(f"{lab}: {got} (want {num})")
    print(f"main.pdf pages={pages} errors={errs} undefined={len(und)} overfull>1pt={sum(1 for o in over if float(o[0])>1)} floats_too_large={len(big)}")
    for l in und[:15]: print("  ",l[:140])
    for o in over: print("   overfull",o[0],"pt, lines",o[1])
    print("float numbers:","all match" if not bad else "; ".join(bad))
if __name__=="__main__": main()
