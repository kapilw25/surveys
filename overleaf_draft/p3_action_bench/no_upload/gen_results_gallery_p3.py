#!/usr/bin/env python3
"""Generate figures/fig_results_gallery.tex: the RESULTS gallery (P1 analog: p1_fig9,
"Results reported across the surveyed systems"). Here it is "Results reported across the surveyed
corpus": a black title bar + 3 evidence-type bands (leaderboard & model-comparison charts /
per-dimension radar & multi-metric / distributions & composition), each a grid of REAL results
plots cropped from the benchmark's arXiv paper (figures/img/results_tiles/<key>.png), per-tile
\\href + name + arXiv id. Provenance in tables/tab_results_provenance.tex. AUTO-GENERATED.

Grouping is by TYPE OF EVIDENCE, the P3 analog of p1_fig9. Only RESULTS/leaderboard/metric figures
are shown (classify-before-compile gate); task/scene figures go to the subject gallery
(fig_subject_gallery). As a benchmark survey, "results" means the leaderboards and metric
comparisons the benchmarks publish; these are sparser and skew to bars/radar/distributions (few
true training curves), so this gallery is smaller than the subject gallery -- benchmarks that
publish no results figure are dropped, not padded. A benchmark may appear more than once when it
reports several evidence types (as systems do in p1_fig9).

Usage:  python3 no_upload/gen_results_gallery_p3.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "figures", "fig_results_gallery.tex"))

def _mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    return re.sub(r'[^a-z0-9]', '', base)

# 3 evidence-type bands: (header, fill-colour macro, [(benchmark name, tile-key), ...])
BANDS = [
    ("Leaderboard \\& model-comparison charts", "rgA", [
        ("World-in-World", "worldinworld"), ("EvalCrafter", "evalcrafter_bars"),
        ("VideoScore", "videoscore"), ("WorldModelBench", "worldmodelbench")]),
    ("Per-dimension radar \\& multi-metric", "rgB", [
        ("VBench", "vbench_radar"), ("EWMBench", "ewmbench"), ("WorldArena", "worldarena"),
        ("EvalCrafter", "evalcrafter_userradar")]),
    ("Distributions \\& composition", "rgC", [
        ("EvalCrafter", "evalcrafter_hist"), ("EvalCrafter", "evalcrafter_pie"),
        ("VBench", "vbench_wordcloud"), ("VideoPhy", "videophy_sunburst")]),
]

COLS = 4
TW, TH = 3.30, 2.64
CGAP, RGAP = 0.06, 0.20
LABEL_H = 0.46
HEAD_H = 0.50
X0 = 0.06
PAGE_W = 13.62
COLPITCH = TW + CGAP
ROWPITCH = TH + LABEL_H + RGAP

def load_ids():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    return {_mkkey(r[0]): r[6].strip('"') for r in rows if r[6] != "null"}

def esc(s):
    return s.replace("&", "\\&").replace("#", "\\#").replace("_", "\\_")

def tile(x, ytop, name, key, idv):
    url = "https://arxiv.org/abs/%s" % idv
    img = "figures/img/results_tiles/%s.png" % key
    nm = esc(name)
    return (
        "\\node[anchor=north west,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{\\includegraphics[width=%.3fcm,height=%.3fcm]{%s}}};\n"
        "\\draw[black!35,line width=0.35pt] (%.3f,%.3f) rectangle (%.3f,%.3f);\n"
        "\\node[anchor=north west,text=ACMDarkBlue,font=\\scriptsize,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{%s}};\n"
        "\\node[anchor=north west,text=black!55,font=\\tiny,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{arXiv:%s}};"
        % (x, ytop, url, TW, TH, img,
           x, ytop, x + TW, ytop - TH,
           x + 0.02, ytop - TH - 0.02, url, nm,
           x + 0.02, ytop - TH - 0.25, url, idv))

def main():
    ids = load_ids()
    missing = [(nm, ky) for _, _, items in BANDS for nm, ky in items if _mkkey(nm) not in ids]
    if missing:
        raise SystemExit("no arXiv id in catalogue for: %s" % missing)

    L = []
    L.append("% RESULTS gallery (P1 analog: p1_fig9). AUTO-GENERATED by no_upload/gen_results_gallery_p3.py.")
    L.append("% Tiles are real results/leaderboard/metric plots cropped from each benchmark's arXiv paper;")
    L.append("% provenance in Table~\\ref{tab:results_provenance}. Grouped by type of evidence.")
    L.append("\\begin{figure*}[p]")
    L.append("\\centering")
    L.append("\\definecolor{rgA}{HTML}{1F618D}\\definecolor{rgB}{HTML}{117A65}"
             "\\definecolor{rgC}{HTML}{B9770E}%")
    L.append("\\resizebox{\\textwidth}{!}{%")
    L.append("\\begin{tikzpicture}[x=1cm,y=1cm]")
    L.append("\\fill[black!88] (0,0) rectangle (%.2f,-0.72);" % PAGE_W)
    L.append("\\node[anchor=west,text=white,font=\\large\\bfseries,inner sep=0] at (0.16,-0.36) "
             "{Results reported across the surveyed corpus};")
    L.append("\\node[anchor=east,text=white!70,font=\\scriptsize,inner sep=0] at (%.2f,-0.36) "
             "{vector, zoomable, per-panel arXiv links};" % (PAGE_W - 0.16))
    y = -0.72
    for head, col, items in BANDS:
        L.append("\\fill[%s!82!black] (0,%.3f) rectangle (%.2f,%.3f);" % (col, y, PAGE_W, y - HEAD_H))
        L.append("\\node[anchor=west,text=white,font=\\footnotesize\\bfseries,inner sep=0] at (0.12,%.3f) {%s};"
                 % (y - HEAD_H / 2, head))
        y -= HEAD_H + 0.07
        n = len(items)
        for i, (nm, ky) in enumerate(items):
            r, c = divmod(i, COLS)
            tiles_in_row = min(COLS, n - r * COLS)          # centre partial rows (no ragged edge)
            row_off = (COLS - tiles_in_row) * COLPITCH / 2.0
            x = X0 + row_off + c * COLPITCH
            ytop = y - r * ROWPITCH
            L.append(tile(x, ytop, nm, ky, ids[_mkkey(nm)]))
        nrows = (len(items) + COLS - 1) // COLS
        y -= nrows * ROWPITCH + 0.10
    L.append("\\end{tikzpicture}}")
    L.append("\\caption{\\textbf{Results reported across the surveyed corpus.} Representative results "
             "figures from the catalogue, grouped by type of evidence: \\emph{leaderboard and "
             "model-comparison charts}, \\emph{per-dimension radar and multi-metric} plots, and "
             "\\emph{distributions and composition}. Each panel is a live hyperlink to the source "
             "paper on arXiv and is annotated with its arXiv id (per-panel provenance in "
             "Table~\\ref{tab:results_provenance}); the figure is vector with plots embedded at full "
             "resolution. Only results/leaderboard/metric figures are shown; task and scene figures "
             "appear in Figure~\\ref{fig:subject_gallery}. As a benchmark survey the reported evidence "
             "is dominated by rankings, radars and distributions rather than training curves, and is "
             "sparser than the subject figures, so this gallery is smaller; benchmarks that publish no "
             "results figure are omitted, not fabricated. A benchmark may appear more than once when "
             "it reports several evidence types. Images \\textcopyright\\ their respective authors, "
             "reproduced for scholarly review.}")
    L.append("\\Description{A gallery of benchmark results figures in three evidence-type bands. The "
             "top band, leaderboard and model-comparison charts, shows four ranking bar charts and "
             "win-rate tables. The middle band, per-dimension radar and multi-metric, shows three "
             "radar plots over evaluation dimensions. The bottom band, distributions and composition, "
             "shows a prompt-length histogram, a meta-type pie chart, and a prompt word cloud. Each "
             "panel is labelled with the benchmark name and its arXiv id.}")
    L.append("\\label{fig:results_gallery}")
    L.append("\\end{figure*}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    n = sum(len(items) for _, _, items in BANDS)
    print("wrote", OUT, "panels:", n)

if __name__ == "__main__":
    main()
