#!/usr/bin/env python3
"""Generate figures/fig_corpus_collage.tex: the two-pole photo-collage hero (P1 analog: p1_fig1).

Same structure and coordinates as P1's fig_corpus_collage: black title bar, two pole header bands,
a centre spine, and a 3x3 tile grid per pole. Each tile is a REAL representative figure harvested
from the benchmark's arXiv paper (figures/img/collage_tiles/<key>.png), hyperlinked to its abstract,
with per-tile provenance in tables/tab_collage_provenance.tex. AUTO-GENERATED; do not hand-edit.

Usage:  python3 no_upload/gen_collage_p3.py
"""
import os, json, re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "figures", "fig_corpus_collage.tex"))

def _mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    return re.sub(r'[^a-z0-9]', '', base)

# 9 per pole (3x3), the subject-verified selection. name -> tile image key.
LEFT = [("LIBERO","libero"),("CALVIN","calvin"),("Meta-World","metaworld"),
        ("ManiSkill2","maniskill2"),("RoboCasa","robocasa"),("Habitat 3.0","habitat30"),
        ("ALFRED","alfred"),("GemBench","gembench"),("VLABench","vlabench")]
RIGHT = [("WorldModelBench","worldmodelbench"),("Physics-IQ","physicsiq"),("WorldScore","worldscore"),
         ("EWMBench","ewmbench"),("EVA-Bench","evabench"),("VideoPhy","videophy"),
         ("Physion++","physionpp"),("Physion","physion"),("EvalCrafter","evalcrafter")]

def load_ids():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    return {_mkkey(r[0]): r[6].strip('"') for r in rows if r[6] != "null"}

# P1 coordinate template (3 cols x 3 rows per pole); tile image 1.803cm wide, 1.402cm tall.
LX = [0.000, 1.873, 3.747]
RX = [8.250, 10.123, 11.997]
RY = [-1.280, -3.057, -4.833]
IMG_W, IMG_H = 1.803, 1.402

def tile(x, y, name, key, idv):
    url = "https://arxiv.org/abs/%s" % idv
    img = "figures/img/collage_tiles/%s.png" % key
    nm = name.replace("&", "\\&").replace("#", "\\#").replace("_", "\\_")
    return (
        "\\node[anchor=north west,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{\\includegraphics[width=%.3fcm,height=%.3fcm]{%s}}};\n"
        "\\draw[black!35,line width=0.35pt] (%.3f,%.3f) rectangle (%.3f,%.3f);\n"
        "\\node[anchor=north west,text=ACMDarkBlue,font=\\tiny,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{%s}};"
        % (x, y, url, IMG_W, IMG_H, img,
           x, y, x + IMG_W, y - IMG_H,
           x + 0.03, y - IMG_H - 0.02, url, nm))

def main():
    ids = load_ids()
    L = []
    L.append("% Thesis hero, two-pole PHOTO collage (P1 analog: fig_corpus_collage / p1_fig1).")
    L.append("% AUTO-GENERATED by no_upload/gen_collage_p3.py. Tiles are real figures harvested from")
    L.append("% each benchmark's arXiv paper; per-tile provenance in Table~\\ref{tab:collage_provenance}.")
    L.append("\\begin{figure*}[tp]")
    L.append("\\centering")
    L.append("\\resizebox{\\textwidth}{!}{%")
    L.append("\\begin{tikzpicture}[x=1cm,y=1cm]")
    # title bar
    L.append("\\fill[black!88] (0,0) rectangle (13.80,-0.72);")
    L.append("\\node[anchor=west,text=white,font=\\large\\bfseries,inner sep=0] at (0.16,-0.36) {Predict or Act?};")
    L.append("\\node[anchor=east,text=white!70,font=\\scriptsize,inner sep=0] at (13.64,-0.36) "
             "{the benchmark landscape on one axis; each tile links to its paper};")
    # pole bands
    L.append("\\fill[cat-vla!70!black] (0,-0.72) rectangle (5.55,-1.22);")
    L.append("\\node[anchor=west,text=white,font=\\footnotesize,inner sep=0] at (0.12,-0.97) "
             "{{\\bfseries CLOSED-LOOP}\\, task-success suites};")
    L.append("\\fill[cat-skill!70!black] (8.25,-0.72) rectangle (13.80,-1.22);")
    L.append("\\node[anchor=west,text=white,font=\\footnotesize,inner sep=0] at (8.37,-0.97) "
             "{{\\bfseries OPEN-LOOP}\\, world-model \\& video eval};")
    # centre spine
    L.append("\\fill[black!5] (5.55,-0.72) rectangle (8.25,-6.55);")
    L.append("\\draw[black!25,line width=0.4pt] (5.55,-0.72)--(5.55,-6.55);")
    L.append("\\draw[black!25,line width=0.4pt] (8.25,-0.72)--(8.25,-6.55);")
    L.append("\\node[text=black,font=\\small\\bfseries,align=center,inner sep=0] at (6.90,-1.95) {what does it\\\\ score?};")
    L.append("\\node[text=black!70,font=\\scriptsize,align=center,inner sep=0] at (6.90,-2.85) {$\\leftarrow$ task success\\\\ (closed loop)};")
    L.append("\\node[text=black,font=\\Large\\bfseries,inner sep=0] at (6.90,-3.60) {vs};")
    L.append("\\node[text=black!70,font=\\scriptsize,align=center,inner sep=0] at (6.90,-4.35) {prediction quality\\\\ (open loop) $\\rightarrow$};")
    L.append("\\node[text=black!55,font=\\scriptsize\\itshape,align=center,text width=2.4cm,inner sep=0] at (6.90,-5.15) {the survey's organising axis};")
    L.append("\\node[text=BrickRed!85!black,font=\\scriptsize\\bfseries,align=center,text width=2.5cm,inner sep=0] at (6.90,-6.05) {only 11 of 160 test if prediction helps action};")
    # tiles
    for i, (nm, ky) in enumerate(LEFT):
        L.append(tile(LX[i % 3], RY[i // 3], nm, ky, ids[ky]))
    for i, (nm, ky) in enumerate(RIGHT):
        L.append(tile(RX[i % 3], RY[i // 3], nm, ky, ids[ky]))
    L.append("\\end{tikzpicture}}")
    L.append("\\caption{\\textbf{Predict or Act?} The survey's organising question, posed with real "
             "benchmarks. \\emph{Closed-loop} (left): policy and embodied suites score task success by "
             "running a policy in the environment. \\emph{Open-loop} (right): world-model and "
             "video-generation benchmarks score prediction or generation quality with no action. The "
             "centre axis is the question neither pole answers, whether prediction earns a closed-loop "
             "advantage, built explicitly by only 11 of 160 benchmarks (Table~\\ref{tab:landscape}). "
             "Every tile is a representative figure from the benchmark's paper and links to it; "
             "per-tile provenance is in Table~\\ref{tab:collage_provenance}. Images \\textcopyright\\ "
             "their respective authors, reproduced for scholarly review.}")
    L.append("\\Description{A two-pole collage of benchmark figures. A black title bar reads ``Predict "
             "or Act?''. The left band, CLOSED-LOOP, shows nine policy and embodied benchmark figures; "
             "the right band, OPEN-LOOP, shows nine world-model and video-generation benchmark figures; "
             "a centre spine contrasts task success (closed loop) with prediction quality (open loop) "
             "and notes that only 11 of 160 build the contrast.}")
    L.append("\\label{fig:corpus_collage}")
    L.append("\\end{figure*}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT, "tiles:", len(LEFT) + len(RIGHT))

if __name__ == "__main__":
    main()
