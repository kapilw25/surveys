#!/usr/bin/env python3
"""Generate tables/tab_landscape.tex for the P3 benchmark/evaluation survey.

Reads the CANONICAL data source, docs/assets/catalog_p3.js (the 158 web-verified
benchmarks), and emits a scriptsize acmart longtable grouped by lane, with a
capability sub-tier and the VLA-vs-WM mark. Reproducible: re-run after any catalog
edit. AUTO-GENERATED; do not hand-edit the .tex.

Rows cite refs.bib via \\cite (numbered references, matching P1 Table 11). The
bibkey scheme here MUST match refs.bib (see mkkey). Set LINK_MODE="href" only for a
standalone arXiv-linked variant.

Usage:  python3 no_upload/gen_landscape_p3.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "tables", "tab_landscape.tex"))
LINK_MODE = "cite"  # "href" | "cite"

LANE_ORDER = ["policy", "embodied", "wmeval", "bridge"]
LANE_LABEL = {
    "policy": "Policy / manipulation suites",
    "embodied": "Embodied navigation, planning \\& social",
    "wmeval": "World-model \\& video-generation evaluation",
    "bridge": "Bridges (prediction to action)",
}
EVAL_LABEL = {"open": "open", "closed": "closed", "bridge": "bridge"}
CON_MARK = {"": "\\dm", "p": "\\pp", "y": "\\yy"}  # model-agnostic / partial / explicit

# capability -> coarse cluster (sub-tier header), by substring priority
CLUSTERS = [
    ("counterfactual", "Counterfactual reasoning"),
    ("hidden-state", "Hidden-state / object permanence"),
    ("theory-of-mind", "Theory of mind"),
    ("social", "Social \\& multi-agent"),
    ("vln", "Vision-language navigation"),
    ("driving", "Autonomous driving"),
    ("locomotion", "Locomotion"),
    ("eqa", "Embodied question answering"),
    ("long-horizon", "Long-horizon \\& planning"),
    ("task-planning", "Long-horizon \\& planning"),
    ("planning", "Long-horizon \\& planning"),
    ("dexterous", "Dexterous manipulation"),
    ("grasp", "Dexterous manipulation"),
    ("deformable", "Deformable-object manipulation"),
    ("pick", "Manipulation"),
    ("stacking", "Manipulation"),
    ("assembly", "Manipulation"),
    ("kitchen", "Manipulation"),
    ("manipulation", "Manipulation"),
    ("skills", "Manipulation"),
    ("rearrangement", "Navigation"),
    ("navigation", "Navigation"),
    ("generaliz", "Generalization \\& robustness"),
    ("transfer", "Generalization \\& robustness"),
    ("robustness", "Generalization \\& robustness"),
    ("world model", "Generative world models"),
    ("physical", "Physical reasoning"),
    ("physics", "Physical reasoning"),
    ("intuitive", "Physical reasoning"),
    ("generation", "Generation quality"),
    ("quality", "Generation quality"),
    ("video", "Generation quality"),
    ("story", "Generation quality"),
    ("hallucination", "Generation quality"),
    ("compositional", "Generation quality"),
    ("alignment", "Generation quality"),
    ("temporal", "Generation quality"),
]

def cluster(cap):
    c = cap.lower()
    for key, label in CLUSTERS:
        if key in c:
            return label
    return "Other"

def tex_escape(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}")]:
        s = s.replace(a, b)
    return s

def mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    k = re.sub(r'[^a-z0-9]', '', base)
    return k or re.sub(r'[^a-z0-9]', '', name.lower())

def link(row):
    nm = "\\textbf{" + tex_escape(row["name"]) + "}"
    idv = row["id"]
    if idv == "null" or not idv:
        return nm
    idv = idv.strip('"')
    if LINK_MODE == "cite":
        return nm + "~\\cite{" + row["key"] + "}"
    return "\\href{https://arxiv.org/abs/" + idv + "}{" + nm + "}"

def load():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    data = [{"name": r[0], "lane": r[1], "cap": r[2], "eval": r[3],
             "con": r[4], "year": int(r[5]), "id": r[6]} for r in rows]
    seen = {}
    for d in data:  # assign bibkeys in catalog order (matches refs.bib), disambiguate collisions
        k = mkkey(d["name"])
        if k in seen:
            k = k + str(d["year"])
        seen[k] = 1
        d["key"] = k
    return data

def main():
    data = load()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    L = []
    L.append("% The broader benchmark landscape for predictive embodied intelligence.")
    L.append("% AUTO-GENERATED by no_upload/gen_landscape_p3.py from docs/assets/catalog_p3.js; do not hand-edit.")
    L.append("{\\scriptsize")
    L.append("\\setlength{\\tabcolsep}{4pt}")
    L.append("\\renewcommand{\\arraystretch}{1.12}")
    L.append("\\begin{longtable}{@{}p{0.30\\textwidth} c >{\\raggedright\\arraybackslash}p{0.34\\textwidth} c c@{}}")
    L.append("\\caption{\\textbf{The robot-evaluation benchmark landscape: %d web-verified benchmarks, "
             "compared on four axes.} Grouped into four evaluation lanes and sub-grouped by capability. "
             "Columns: \\textbf{Year}; \\textbf{Capability} (what the benchmark stresses); \\textbf{Eval} "
             "(evaluation mode: open-loop prediction/generation quality, closed-loop task success, or a "
             "prediction-to-action bridge); and \\textbf{VLA vs WM} (does the benchmark build a native "
             "direct-policy vs world-model contrast: \\yy\\ explicit, \\pp\\ partial, \\dm\\ model-agnostic). "
             "Every entry is a real, individually citeable benchmark.}"
             "\\label{tab:landscape}\\\\" % len(data))
    header = ("\\toprule\n\\textbf{Benchmark} & \\textbf{Year} & \\textbf{Capability} & "
              "\\textbf{Eval} & \\textbf{VLA vs WM}\\\\\n\\midrule")
    L.append(header)
    L.append("\\endfirsthead")
    L.append("\\multicolumn{5}{@{}l}{\\scriptsize\\emph{Table~\\ref{tab:landscape} (continued)}}\\\\")
    L.append(header)
    L.append("\\endhead")
    L.append("\\bottomrule")
    L.append("\\endlastfoot")

    for lane in LANE_ORDER:
        lane_rows = [r for r in data if r["lane"] == lane]
        if not lane_rows:
            continue
        L.append("\\multicolumn{5}{@{}l}{\\rule{0pt}{2.8ex}\\textbf{\\textsf{%s}}~\\textcolor{gray}{(%d)}}\\\\[1pt]"
                 % (LANE_LABEL[lane], len(lane_rows)))
        # group by capability cluster
        groups = {}
        for r in lane_rows:
            groups.setdefault(cluster(r["cap"]), []).append(r)
        for cl in sorted(groups, key=lambda k: (-len(groups[k]), k)):
            rows = sorted(groups[cl], key=lambda r: r["name"].lower())
            L.append("\\multicolumn{5}{@{}l}{\\hspace{0.6em}\\emph{%s}}\\\\" % cl)
            for r in rows:
                L.append("\\hspace{0.6em}%s & %d & %s & \\textsf{%s} & %s\\\\" % (
                    link(r), r["year"], tex_escape(r["cap"]),
                    EVAL_LABEL.get(r["eval"], r["eval"]), CON_MARK.get(r["con"], "\\dm")))
    L.append("\\end{longtable}")
    L.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT, "rows:", len(data), "lanes:",
          {l: sum(1 for r in data if r["lane"] == l) for l in LANE_ORDER})

if __name__ == "__main__":
    main()
