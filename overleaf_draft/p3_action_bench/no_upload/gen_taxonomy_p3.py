#!/usr/bin/env python3
"""Generate figures/fig_taxonomy_main.tex: the hero grouped-cell benchmark taxonomy.

EXACT-structure replica of P1's fig_taxonomy_main (p1_fig2): a forest (grow=east) organised
root -> evaluation lane -> capability cluster -> terminal cell, where every cell line is
"\\textbf{Name}: <what it measures>~\\citep{key}" (mirroring P1's "Name: trimmed title [cite]").
Graduated fonts, one-page figure*[p] scaled to fill the text height, and the frontier lane
(bridges) shaded to mark the survey's novelty axis. Reproducible from docs/assets/catalog_p3.js;
same bibkey scheme as gen_landscape_p3.py so every cite resolves. AUTO-GENERATED; do not hand-edit.

Usage:  python3 no_upload/gen_taxonomy_p3.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "figures", "fig_taxonomy_main.tex"))

# lane -> (label, category fill, leaf fill, #clusters to show, #benchmarks per cluster)
LANES = [
    ("policy",   "\\S3.1 Policy suites", "cat-vla",  "leaf-vla",  4, 8),
    ("embodied", "\\S3.2 Embodied agents", "cat-code", "leaf-code", 6, 7),
    ("wmeval",   "\\S3.3 World-model eval", "cat-skill", "leaf-skill", 4, 8),
    ("bridge",   "\\S3.4 Bridges", "secE", "secEl", 1, 6),
]

CLUSTERS = [
    ("counterfactual","Counterfactual"),("hidden-state","Hidden-state"),("theory-of-mind","Theory of mind"),
    ("social","Social \\& multi-agent"),("vln","Vision-language nav."),("driving","Autonomous driving"),
    ("locomotion","Locomotion"),("eqa","Embodied QA"),("long-horizon","Long-horizon"),
    ("task-planning","Long-horizon"),("planning","Long-horizon"),("dexterous","Dexterous"),
    ("grasp","Dexterous"),("deformable","Deformable"),("pick","Manipulation"),("stacking","Manipulation"),
    ("assembly","Manipulation"),("kitchen","Manipulation"),("manipulation","Manipulation"),
    ("skills","Manipulation"),("rearrangement","Navigation"),("navigation","Navigation"),
    ("generaliz","Generalization"),("transfer","Generalization"),("robustness","Generalization"),
    ("world model","Generative world models"),("physical","Physical reasoning"),("physics","Physical reasoning"),
    ("intuitive","Physical reasoning"),("generation","Generation quality"),("quality","Generation quality"),
    ("video","Generation quality"),("story","Generation quality"),("hallucination","Generation quality"),
    ("compositional","Generation quality"),("alignment","Generation quality"),("temporal","Generation quality"),
]

def cluster(cap):
    c = cap.lower()
    for k, l in CLUSTERS:
        if k in c:
            return l
    return "Other"

def tex_escape(s):
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")]:
        s = s.replace(a, b)
    return s

def mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    k = re.sub(r'[^a-z0-9]', '', base)
    return k or re.sub(r'[^a-z0-9]', '', name.lower())

def trim(cap, n=52):
    cap = cap.strip()
    return cap if len(cap) <= n else cap[:n-1].rstrip() + "\\ldots"

def load():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    data, seen = [], {}
    for r in rows:
        k = mkkey(r[0])
        if k in seen:
            k = k + r[5]
        seen[k] = 1
        data.append({"name": r[0], "lane": r[1], "cap": r[2], "key": k, "id": r[6]})
    return data

def main():
    data = load()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    L = []
    L.append("% HERO taxonomy -- AUTO-GENERATED by no_upload/gen_taxonomy_p3.py; do not hand-edit.")
    L.append("\\begin{figure*}[p]")
    L.append("\\centering")
    L.append("\\resizebox{!}{0.9\\textheight}{%")
    L.append("\\begin{forest}")
    L.append("  for tree={align=center},")
    L.append("  where level=0{font=\\Large, text width=10.5em}{},")
    L.append("  where level=1{font=\\large, text width=13em}{},")
    L.append("  where level=2{font=\\normalsize, text width=12.5em}{},")
    L.append("  where level=3{font=\\footnotesize, text width=33em, align=left}{},")
    L.append("[\\textbf{Robot-evaluation}\\\\\\textbf{benchmarks for}\\\\\\textbf{predictive}\\\\"
             "\\textbf{embodied AI}, fill=tx-root, text width=10.5em")
    shown = 0
    for lane_i, (lane, label, catfill, leaffill, ncl, nbe) in enumerate(LANES, start=1):
        rows = [d for d in data if d["lane"] == lane]
        groups = {}
        for r in rows:
            groups.setdefault(cluster(r["cap"]), []).append(r)
        top = sorted(groups, key=lambda k: (-len(groups[k]), k))[:ncl]
        L.append("  [\\textbf{%s}, fill=%s" % (label, catfill))
        for cl_i, cl in enumerate(top, start=1):
            items = sorted(groups[cl], key=lambda r: (r["id"] == "null", r["name"].lower()))[:nbe]
            lines = []
            for r in items:
                nm = "\\textbf{%s}" % tex_escape(r["name"])
                cite = "" if r["id"] == "null" else "~\\citep{%s}" % r["key"]
                lines.append("%s: %s%s" % (nm, tex_escape(trim(r["cap"])), cite))
                shown += 1
            cell = "\\\\".join(lines)
            L.append("    [\\textbf{\\S3.%d.%d %s}, fill=%s" % (lane_i, cl_i, cl, catfill))
            L.append("      [{%s}, fill=%s]" % (cell, leaffill))
            L.append("    ]")
        L.append("  ]")
    L.append("]")
    L.append("\\end{forest}}")
    L.append("\\caption{\\textbf{A taxonomy of robot-evaluation benchmarks for predictive embodied "
             "intelligence} (%d representative benchmarks of the %d in Table~\\ref{tab:landscape}). "
             "Each sub-family is one cell listing its benchmarks, each with a short statement of what "
             "it measures. Benchmarks are grouped by evaluation lane (\\S3.1--\\S3.4) and then by the "
             "capability they stress. The lanes run from closed-loop task-success suites to the "
             "\\emph{bridge} frontier (shaded), the only lane that turns prediction into executed "
             "action, which is the survey's novelty axis. Full per-benchmark detail: "
             "Tables~\\ref{tab:compare_main}, \\ref{tab:landscape}.}" % (shown, len(data)))
    L.append("\\Description{A tree diagram organising representative robot-evaluation benchmarks under "
             "the root ``robot-evaluation benchmarks for predictive embodied AI'' into four evaluation "
             "lanes (policy and manipulation suites; embodied navigation, planning and social; "
             "world-model and video-generation evaluation; and prediction-to-action bridges), each "
             "split into capability clusters whose cells list benchmarks with what each measures.}")
    L.append("\\label{fig:taxonomy_main}")
    L.append("\\end{figure*}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT, "shown:", shown, "of", len(data))

if __name__ == "__main__":
    main()
