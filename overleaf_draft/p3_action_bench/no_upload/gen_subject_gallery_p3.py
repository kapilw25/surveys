#!/usr/bin/env python3
"""Generate figures/fig_subject_gallery.tex: the SUBJECT gallery (P1 analog: p1_fig8,
"Robots across the surveyed systems"). Here it is "Benchmarks across the surveyed corpus":
a black title bar + 3 coloured lane bands (closed-loop suites / world-model & video eval /
prediction-to-action bridges), each a grid of REAL task/scene figures cropped from the
benchmark's arXiv paper (figures/img/subject_tiles/<key>.png), per-tile \\href + name +
arXiv id. Per-panel provenance in tables/tab_panel_provenance.tex. AUTO-GENERATED; do not hand-edit.

Grouping is by evaluation lane (the survey's organising axis), the P3 analog of p1_fig8's
embodiment grouping: p1's subjects are robots (grouped by hardware), ours are benchmarks
(grouped by what they score). Only SUBJECT scenes are shown (classify-before-compile gate);
results/leaderboard figures go to the results gallery (fig_results_gallery). A benchmark with
no locatable subject figure is dropped, never guessed.

Usage:  python3 no_upload/gen_subject_gallery_p3.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "figures", "fig_subject_gallery.tex"))

def _mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    return re.sub(r'[^a-z0-9]', '', base)

# 3 lane bands, each: (header text, fill colour macro, [(name, tile-key), ...])
BANDS = [
    ("CLOSED-LOOP task-success suites", "sgClosed", [
        ("ALFRED", "alfred"), ("BEHAVIOR-1K", "behavior1k"), ("CALVIN", "calvin"),
        ("GemBench", "gembench"), ("ManiSkill2", "maniskill2"), ("Meta-World", "metaworld"),
        ("RoboCasa", "robocasa"), ("LIBERO", "libero"), ("VLABench", "vlabench"),
        ("Habitat 3.0", "habitat30")]),
    ("OPEN-LOOP world-model \\& video-generation evaluation", "sgWM", [
        ("EVA-Bench", "evabench"), ("EWMBench", "ewmbench"), ("Physics-IQ", "physicsiq"),
        ("Physion", "physion"), ("Physion++", "physionpp"), ("VideoPhy", "videophy"),
        ("WorldModelBench", "worldmodelbench"), ("WorldScore", "worldscore"),
        ("VBench-2.0", "vbench20"), ("WorldPrediction", "worldprediction")]),
    ("PREDICTION-TO-ACTION bridges", "sgBridge", [
        ("WorldSimBench", "worldsimbench"), ("World-in-World", "worldinworld"),
        ("RoboWM-Bench", "robowmbench"), ("WorldArena", "worldarena")]),
]

# geometry (cm; y grows downward as negative)
COLS = 5
TW, TH = 2.66, 2.128          # tile image w,h (aspect 480x384=1.25)
CGAP, RGAP = 0.05, 0.17       # column / row gaps
LABEL_H = 0.46                # 2 label lines (name + arXiv id)
HEAD_H = 0.50                 # band header strip
X0 = 0.06
PAGE_W = 13.80
COLPITCH = TW + CGAP
ROWPITCH = TH + LABEL_H + RGAP

def load_ids():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    return {_mkkey(r[0]): r[6].strip('"') for r in rows if r[6] != "null"}

def esc(s):
    return s.replace("&", "\\&").replace("#", "\\#").replace("_", "\\_")

def tile(x, ytop, name, key, idv):
    url = "https://arxiv.org/abs/%s" % idv
    img = "figures/img/subject_tiles/%s.png" % key
    nm = esc(name)
    return (
        "\\node[anchor=north west,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{\\includegraphics[width=%.3fcm,height=%.3fcm]{%s}}};\n"
        "\\draw[black!35,line width=0.35pt] (%.3f,%.3f) rectangle (%.3f,%.3f);\n"
        "\\node[anchor=north west,text=ACMDarkBlue,font=\\scriptsize,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{%s}};\n"
        "\\node[anchor=north west,text=black!55,font=\\tiny,inner sep=0] at (%.3f,%.3f) "
        "{\\href{%s}{arXiv:%s}};"
        % (x, ytop, url, TW, TH, img,
           x, ytop, x + TW, ytop - TH,
           x + 0.02, ytop - TH - 0.02, url, nm,
           x + 0.02, ytop - TH - 0.25, url, idv))

def main():
    ids = load_ids()
    # sanity: every tile key resolves to a catalogue arXiv id and a tile file exists
    missing = []
    for _, _, items in BANDS:
        for nm, ky in items:
            if ky not in ids:
                missing.append((nm, ky))
    if missing:
        raise SystemExit("no arXiv id in catalogue for: %s" % missing)

    L = []
    L.append("% SUBJECT gallery (P1 analog: p1_fig8). AUTO-GENERATED by no_upload/gen_subject_gallery_p3.py.")
    L.append("% Tiles are real subject/scene figures cropped from each benchmark's arXiv paper;")
    L.append("% per-panel provenance in Table~\\ref{tab:panel_provenance}. Grouped by evaluation lane.")
    L.append("\\begin{figure*}[p]")
    L.append("\\centering")
    L.append("\\definecolor{sgClosed}{HTML}{1E8449}\\definecolor{sgWM}{HTML}{C2185B}"
             "\\definecolor{sgBridge}{HTML}{7C3AED}%")
    L.append("\\resizebox{\\textwidth}{!}{%")
    L.append("\\begin{tikzpicture}[x=1cm,y=1cm]")
    # title bar
    L.append("\\fill[black!88] (0,0) rectangle (%.2f,-0.72);" % PAGE_W)
    L.append("\\node[anchor=west,text=white,font=\\large\\bfseries,inner sep=0] at (0.16,-0.36) "
             "{Benchmarks across the surveyed corpus};")
    L.append("\\node[anchor=east,text=white!70,font=\\scriptsize,inner sep=0] at (%.2f,-0.36) "
             "{vector, zoomable, per-panel arXiv links};" % (PAGE_W - 0.16))
    y = -0.72
    for head, col, items in BANDS:
        # band header strip
        L.append("\\fill[%s!78!black] (0,%.3f) rectangle (%.2f,%.3f);" % (col, y, PAGE_W, y - HEAD_H))
        L.append("\\node[anchor=west,text=white,font=\\footnotesize\\bfseries,inner sep=0] at (0.12,%.3f) {%s};"
                 % (y - HEAD_H / 2, head))
        y -= HEAD_H + 0.07
        for i, (nm, ky) in enumerate(items):
            r, c = divmod(i, COLS)
            x = X0 + c * COLPITCH
            ytop = y - r * ROWPITCH
            L.append(tile(x, ytop, nm, ky, ids[ky]))
        nrows = (len(items) + COLS - 1) // COLS
        y -= nrows * ROWPITCH + 0.10
    L.append("\\end{tikzpicture}}")
    L.append("\\caption{\\textbf{Benchmarks across the surveyed corpus.} Representative subject "
             "figures from the catalogue, grouped by evaluation lane rather than embodiment: "
             "\\emph{closed-loop} task-success suites, \\emph{open-loop} world-model and "
             "video-generation evaluation, and the \\emph{prediction-to-action bridges}. Each panel "
             "is a live hyperlink to the source paper on arXiv and is annotated with its arXiv id "
             "(per-panel figure provenance in Table~\\ref{tab:panel_provenance}); the figure is vector "
             "with photographs embedded at full resolution, so it can be zoomed without pixelation. "
             "Only figures that depict the benchmark's task or scene are shown; results and "
             "leaderboard figures appear in Figure~\\ref{fig:results_gallery}. Benchmarks with no "
             "locatable subject figure are omitted, not fabricated. Images \\textcopyright\\ their "
             "respective authors, reproduced for scholarly review.}")
    L.append("\\Description{A gallery of benchmark subject figures in three lane bands. The top band, "
             "closed-loop task-success suites, shows ten policy and embodied benchmark scenes (robot "
             "arms and simulated households). The middle band, open-loop world-model and "
             "video-generation evaluation, shows ten generated-video or physical-scene samples. The "
             "bottom band, prediction-to-action bridges, shows four world-model benchmark scenes. Each "
             "panel is labelled with the benchmark name and its arXiv id.}")
    L.append("\\label{fig:subject_gallery}")
    L.append("\\end{figure*}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    n = sum(len(items) for _, _, items in BANDS)
    print("wrote", OUT, "panels:", n)

if __name__ == "__main__":
    main()
