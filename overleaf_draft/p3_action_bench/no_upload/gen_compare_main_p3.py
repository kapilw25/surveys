#!/usr/bin/env python3
"""Generate tables/tab_compare_main.tex: a representative-benchmark comparison longtable.

P1 analog: Table 2 (tab_compare_main). Pulls Year / Eval / Capability / VLA-vs-WM contrast
from the CANONICAL catalog (docs/assets/catalog_p3.js) and injects only the peer-reviewed VENUE
(web-verified by a parallel audit agent). Grouped by evaluation lane. Uses \\cite with the SAME
bibkey scheme as gen_landscape_p3.py / refs.bib. AUTO-GENERATED; do not hand-edit the .tex.

Usage:  python3 no_upload/gen_compare_main_p3.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets", "catalog_p3.js"))
OUT = os.path.normpath(os.path.join(HERE, "..", "tables", "tab_compare_main.tex"))

LANE_ORDER = ["policy", "embodied", "wmeval", "bridge"]
LANE_LABEL = {
    "policy":   "\\S3.1 Policy / manipulation suites",
    "embodied": "\\S3.2 Embodied navigation, planning \\& social",
    "wmeval":   "\\S3.3 World-model \\& video-generation evaluation",
    "bridge":   "\\S3.4 Bridges (prediction to action)",
}
LANE_TAG = {"policy": "\\dclosed", "embodied": "\\dclosed", "wmeval": "\\dopen", "bridge": "\\dbridge"}
EVMARK = {"open": "\\dopen", "closed": "\\dclosed", "bridge": "\\dbridge"}
CON_MARK = {"": "\\dm", "p": "\\pp", "y": "\\yy"}

# Representative benchmarks per lane (exact catalog names), in display order.
REP = {
    "policy":   ["CALVIN", "LIBERO", "Meta-World", "ManiSkill2", "SIMPLER / SimplerEnv",
                 "THE COLOSSEUM", "RoboCasa", "RoboArena", "GemBench", "VLABench"],
    "embodied": ["Habitat 3.0", "BEHAVIOR-1K", "ALFRED", "TEACh", "RoboTHOR",
                 "SocNavBench", "LIBERO-Mem", "VIMA-Bench"],
    "wmeval":   ["WorldModelBench", "Physics-IQ", "VBench-2.0", "WorldScore", "EWMBench",
                 "EVA-Bench", "WorldPrediction", "Physion", "Physion++"],
    "bridge":   ["WorldSimBench", "World-in-World", "RoboWM-Bench", "WorldArena"],
}
# Peer-reviewed venue (web-verified by audit agent); "arXiv" = preprint-only.
VENUE = {
    "CALVIN": "RA-L", "LIBERO": "NeurIPS D\\&B", "Meta-World": "CoRL", "ManiSkill2": "ICLR",
    "SIMPLER / SimplerEnv": "CoRL", "THE COLOSSEUM": "RSS", "RoboCasa": "RSS", "RoboArena": "CoRL",
    "GemBench": "ICRA", "VLABench": "ICCV", "Habitat 3.0": "ICLR", "BEHAVIOR-1K": "CoRL",
    "ALFRED": "CVPR", "TEACh": "AAAI", "RoboTHOR": "CVPR", "SocNavBench": "ACM THRI",
    "LIBERO-Mem": "AAAI", "VIMA-Bench": "ICML", "WorldModelBench": "arXiv", "Physics-IQ": "WACV",
    "VBench-2.0": "arXiv", "WorldScore": "ICCV", "EWMBench": "arXiv", "EVA-Bench": "ICML",
    "WorldPrediction": "arXiv", "Physion": "NeurIPS D\\&B", "Physion++": "NeurIPS D\\&B",
    "WorldSimBench": "ICML", "World-in-World": "ICLR", "RoboWM-Bench": "arXiv", "WorldArena": "arXiv",
}
# Short display override for over-long catalog names.
DISPLAY = {"SIMPLER / SimplerEnv": "SIMPLER", "THE COLOSSEUM": "THE COLOSSEUM"}

def tex_escape(s):
    for a, b in [("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_")]:
        s = s.replace(a, b)
    return s

def mkkey(name):
    base = name.split("(")[0].split("/")[0].strip().lower().replace("+", "p")
    k = re.sub(r'[^a-z0-9]', '', base)
    return k or re.sub(r'[^a-z0-9]', '', name.lower())

def load():
    src = open(CATALOG, encoding="utf-8").read()
    block = src.split("var DATA = [", 1)[1].split("].map", 1)[0]
    rows = re.findall(
        r'\["([^"]+)",\s*"([^"]+)",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*(\d+),\s*(null|"[^"]*")\]',
        block)
    by = {}
    seen = {}
    for r in rows:
        k = mkkey(r[0])
        if k in seen:
            k = k + r[5]
        seen[k] = 1
        by[r[0]] = {"name": r[0], "lane": r[1], "cap": r[2], "eval": r[3],
                    "con": r[4], "year": int(r[5]), "id": r[6], "key": k}
    return by

def main():
    by = load()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    total = sum(len(v) for v in REP.values())
    L = []
    L.append("% Table -- representative-benchmark comparison, grouped by evaluation lane.")
    L.append("% AUTO-GENERATED by no_upload/gen_compare_main_p3.py; do not hand-edit.")
    L.append("{\\footnotesize")
    L.append("\\setlength{\\tabcolsep}{5pt}")
    L.append("\\renewcommand{\\arraystretch}{1.15}")
    L.append("\\begin{longtable}{@{}p{0.22\\textwidth} c l c >{\\raggedright\\arraybackslash}p{0.30\\textwidth} c@{}}")
    L.append("\\caption{\\textbf{Detailed comparison of a representative %d of the %d benchmarks} "
             "in the landscape (Table~\\ref{tab:landscape}), grouped by evaluation lane. "
             "\\textbf{Eval}: \\dopen\\ open-loop prediction/generation quality, \\dclosed\\ "
             "closed-loop task success, \\dbridge\\ prediction-to-action bridge. \\textbf{VLA vs WM}: "
             "\\yy\\ native direct-policy vs world-model contrast, \\pp\\ partial, \\dm\\ "
             "model-agnostic. Venues are web-verified; ``arXiv'' marks preprint-only works.}"
             "\\label{tab:compare_main}\\\\" % (total, len(by)))
    header = ("\\toprule\n\\textbf{Benchmark} & \\textbf{Year} & \\textbf{Venue} & \\textbf{Eval} & "
              "\\textbf{Capability} & \\textbf{VLA vs WM}\\\\\n\\midrule")
    L.append(header)
    L.append("\\endfirsthead")
    L.append("\\multicolumn{6}{@{}l}{\\footnotesize\\emph{Table~\\ref{tab:compare_main} (continued)}}\\\\")
    L.append(header)
    L.append("\\endhead")
    L.append("\\bottomrule")
    L.append("\\endlastfoot")

    missing = []
    for lane in LANE_ORDER:
        L.append("\\multicolumn{6}{@{}l}{\\rule{0pt}{2.6ex}\\textbf{\\textsf{%s}} \\hfill %s}\\\\[1pt]"
                 % (LANE_LABEL[lane], LANE_TAG[lane]))
        for nm in REP[lane]:
            r = by.get(nm)
            if r is None:
                missing.append(nm); continue
            disp = DISPLAY.get(nm, nm)
            L.append("\\textbf{%s}~\\cite{%s} & %d & %s & %s & %s & %s\\\\" % (
                tex_escape(disp), r["key"], r["year"], VENUE.get(nm, "arXiv"),
                EVMARK.get(r["eval"], "\\dclosed"), tex_escape(r["cap"]),
                CON_MARK.get(r["con"], "\\dm")))
        L.append("\\midrule")
    if L[-1] == "\\midrule":
        L.pop()
    L.append("\\end{longtable}")
    L.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT, "rows:", total, "missing:", missing)

if __name__ == "__main__":
    main()
